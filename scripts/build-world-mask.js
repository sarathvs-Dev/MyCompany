/**
 * Regenerates src/data/worldMask.js — the dot grid behind the hero world map.
 *
 *   curl -sL -o /tmp/land.geojson \
 *     https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson
 *   node scripts/build-world-mask.js /tmp/land.geojson
 *
 * Rasterises the land polygons onto an equirectangular grid and packs the
 * result 1 bit per cell. Only rerun this if the framing or resolution changes.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/build-world-mask.js <ne_110m_land.geojson>');
  process.exit(1);
}

const COLS = 168;
// Antarctica reads as a distracting bar along the bottom, so the band is clipped.
const BOUNDS = { lonL: -168, lonR: 180, latTop: 76, latBot: -56 };
const cellLon = (BOUNDS.lonR - BOUNDS.lonL) / COLS;
const ROWS = Math.round((BOUNDS.latTop - BOUNDS.latBot) / cellLon); // square cells
const cellLat = (BOUNDS.latTop - BOUNDS.latBot) / ROWS;

const geo = JSON.parse(fs.readFileSync(src, 'utf8'));
const rings = [];
for (const f of geo.features) {
  for (const ring of f.geometry.coordinates) {
    let minX = 180, maxX = -180, minY = 90, maxY = -90;
    for (const [x, y] of ring) {
      if (x < minX) minX = x;
      if (x > maxX) maxX = x;
      if (y < minY) minY = y;
      if (y > maxY) maxY = y;
    }
    rings.push({ ring, minX, maxX, minY, maxY });
  }
}

function inRing(x, y, r) {
  if (x < r.minX || x > r.maxX || y < r.minY || y > r.maxY) return false;
  const pts = r.ring;
  let inside = false;
  for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
    const xi = pts[i][0], yi = pts[i][1], xj = pts[j][0], yj = pts[j][1];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

// several samples per cell so thin features (Japan, the UK, island chains) survive
const SUB = [[0.5, 0.5], [0.2, 0.3], [0.8, 0.3], [0.2, 0.7], [0.8, 0.7]];
const bits = [];
for (let row = 0; row < ROWS; row++) {
  for (let col = 0; col < COLS; col++) {
    let land = 0;
    for (const [fx, fy] of SUB) {
      const lon = BOUNDS.lonL + (col + fx) * cellLon;
      const lat = BOUNDS.latTop - (row + fy) * cellLat;
      if (rings.some((r) => inRing(lon, lat, r))) { land = 1; break; }
    }
    bits.push(land);
  }
}

const bytes = [];
for (let i = 0; i < bits.length; i += 8) {
  let b = 0;
  for (let k = 0; k < 8; k++) b = (b << 1) | (bits[i + k] || 0);
  bytes.push(b);
}
const b64 = Buffer.from(bytes).toString('base64');

const out = `// Generated by scripts/build-world-mask.js from Natural Earth 110m land polygons.
// Equirectangular grid, 1 bit per cell, packed MSB-first and base64 encoded.
export const GRID = { cols: ${COLS}, rows: ${ROWS} };

// projection bounds used when rasterising (also maps city lat/lon onto the grid)
export const BOUNDS = { lonL: ${BOUNDS.lonL}, lonR: ${BOUNDS.lonR}, latTop: ${BOUNDS.latTop}, latBot: ${BOUNDS.latBot} };

const MASK =
  '${b64}';

/** Grid coordinates of every land cell, decoded once. */
export function landCells() {
  const bin = atob(MASK);
  const cells = [];
  for (let i = 0; i < GRID.cols * GRID.rows; i++) {
    if (bin.charCodeAt(i >> 3) & (128 >> (i & 7))) {
      cells.push([i % GRID.cols, (i / GRID.cols) | 0]);
    }
  }
  return cells;
}

/** Lat/lon -> fractional grid coordinates. */
export function project(lat, lon) {
  return [
    ((lon - BOUNDS.lonL) / (BOUNDS.lonR - BOUNDS.lonL)) * GRID.cols,
    ((BOUNDS.latTop - lat) / (BOUNDS.latTop - BOUNDS.latBot)) * GRID.rows,
  ];
}
`;

const here = path.dirname(fileURLToPath(import.meta.url));
const dest = path.join(here, '..', 'src', 'data', 'worldMask.js');
fs.writeFileSync(dest, out);
console.log(`${COLS}x${ROWS}, ${bits.reduce((a, b) => a + b, 0)} land cells -> ${dest}`);
